// Converts raw dumps of the legacy galleria.ge API (scripts/raw/*.json) into
// the normalized mock data the new front end reads (src/data/*.json).
// Once the Django API is live this script is no longer needed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const raw = (name) => JSON.parse(readFileSync(join(root, 'scripts/raw', name), 'utf8'));
const out = (name, data) =>
  writeFileSync(join(root, 'src/data', name), JSON.stringify(data, null, 2) + '\n');

const CATEGORY = { 1: 'shops', 2: 'food', 3: 'entertainment', 4: 'services' };

const slugOf = (url) => url.replace(/^https?:\/\/[^/]+\//, '').replace(/\/$/, '');
const hhmm = (t) => (t ? t.slice(0, 5) : null);
const isoDate = (d) => {
  const [dd, mm, yyyy] = d.split('.');
  return `${yyyy}-${mm}-${dd}`;
};

// Wayfinder unit ids per store ("2.14" = floor 2, unit 14). A store can span
// several units and floors (H&M, Cavea).
const placesBySlug = Object.fromEntries(
  raw('sartulebi.json').pageData.map((p) => [slugOf(p.shopUrl), p.shop_place.split(',').map((s) => s.trim())]),
);

const stores = ['magaziebi', 'kveba', 'gartoba', 'servisebi']
  .flatMap((file) => raw(`${file}.json`).pageData)
  .map((s) => ({
    slug: slugOf(s.url),
    name: s.name.trim(),
    logo: s.logoUrl,
    phone: s.phone?.trim() || null,
    hours:
      s.hours?.from && s.hours.from !== s.hours.to
        ? { from: hhmm(s.hours.from), to: hhmm(s.hours.to) }
        : null,
    floor: s.floorNumber ?? null,
    places: placesBySlug[slugOf(s.url)] ?? [],
    category: CATEGORY[s.category_id],
    subcategories: s.subcategories.map(Number),
    audience: s.genders ?? [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }));

const offers = raw('shetavazebebi.json').pageData.map((o, i) => ({
  id: i + 1,
  store: slugOf(o.shopUrl),
  storeName: o.title.replace(/^sale at\s*/i, '').trim(),
  logo: o.logoUrl,
  badge: o.cover?.text ?? null,
  description: o.description.trim(),
  date: isoDate(o.date),
  category: o.category_name,
}));

const news = raw('ambebi.json').pageData.map((n) => ({
  slug: slugOf(n.url),
  title: n.title.trim(),
  cover: n.cover?.img ?? null,
  date: isoDate(n.date),
  excerpt: n.description.trim(),
}));

// Subcategory labels (raw/filter.json) are translated by hand in src/lib/categories.ts.

out('stores.json', stores);
out('offers.json', offers);
out('news.json', news);

// Brand logo as a React component, so it can take currentColor.
const logo = (file) => {
  const s = readFileSync(join(root, 'scripts/raw', file), 'utf8');
  return {
    viewBox: s.match(/viewBox="([^"]+)"/)[1],
    body: s.replace(/^<symbol[^>]*>/, '').replace(/<\/symbol>$/, '').replace(/\s*class="[^"]*"/g, ''),
  };
};
const en = logo('galleria-tbilisi-logo-en.svg');
const ka = logo('galleria-tbilisi-logo-ka.svg');
writeFileSync(
  join(root, 'src/components/logoPaths.ts'),
  `// Generated by scripts/build-data.mjs from the legacy site's SVG sprite.\n` +
    `export const LOGO = ${JSON.stringify({ en, ka }, null, 2)} as const;\n`,
);

console.log(`stores ${stores.length}, offers ${offers.length}, news ${news.length}`);
